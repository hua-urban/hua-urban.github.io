import assert from 'node:assert/strict';
import * as THREE from '../industry-islands/lib/three.module.js';
import {createCatInteractions} from '../industry-islands/e/cat-interactions.js';
const root = new THREE.Group(); root.name = 'garden-tabby'; root.position.y = .17;
root.scale.setScalar(.9); root.rotation.y = .6;
const body = new THREE.Group(); body.name = 'cat-body'; root.add(body);
const torso = new THREE.Mesh(new THREE.SphereGeometry(1, 8, 6)); torso.position.y = .3; torso.scale.set(.2,.2,.3); body.add(torso);
for (const name of ['cat-head','cat-leg-front-left','cat-leg-front-right','cat-leg-back-left','cat-leg-back-right','cat-tail-0']) {
 const node = new THREE.Group(); node.name = name; node.position.set(.1,.25,.1); node.rotation.set(.03,.04,.02); body.add(node);
 const shape = new THREE.Mesh(new THREE.CylinderGeometry(1,1,1,8)); shape.scale.set(.04,.18,.04); shape.position.y = -.1; node.add(shape);
}
let calls = 0;
const api = createCatInteractions({actors:[{root, update:()=>{calls++; root.position.x += .001;}}],random:()=>0});
const transforms = () => { const out=[]; body.traverse(n=>out.push([...n.position,...n.quaternion,...n.scale])); return out; };
const initial = transforms();
for(let i=0;i<359;i++) api.update(i*.05,.05);
assert.equal(api.getState()[0].action,null);
for(let i=0;i<2;i++) api.update(18+i*.05,.05);
assert.equal(api.getState()[0].action,'scratch');
const frozenRoot = [...root.position,...root.quaternion,...root.scale]; const frozenCalls = calls;
for(let i=0;i<8;i++) api.update(19,.05);
assert.equal(calls,frozenCalls); assert.deepEqual([...root.position,...root.quaternion,...root.scale],frozenRoot);
const state = api.getState(); api.update(100,0); assert.deepEqual(api.getState(),state);
assert(api.pet(root.name)); assert.equal(api.getState()[0].action,'belly');
for(let i=0;i<8;i++)api.update(20,.05);assert(Math.abs(body.rotation.z)<.05,'Crouch before rolling');
for(let i=0;i<18;i++)api.update(20,.05);assert(Math.abs(body.rotation.z)>.9&&Math.abs(body.rotation.z)<1.4,'Settle onto a side first');
for(let i=0;i<18;i++)api.update(20,.05);assert(Math.abs(body.rotation.z)>1.9&&Math.abs(body.rotation.z)<2.1,'Expose belly gently without a rigid half-turn');
root.updateMatrixWorld(true);
body.traverse(n=>{ if(!n.geometry)return; const e=n.matrixWorld.elements; const r=n.geometry.type==='CylinderGeometry'?Math.hypot(e[1],e[9])+.5*Math.abs(e[5]):Math.hypot(e[1],e[5],e[9]); assert(e[13]-r>=.178-1e-9); });
assert(api.pet(root.name)); assert.equal(api.getState()[0].elapsed,0);
for(let i=0;i<120;i++) api.update(25,.05);
assert.equal(api.getState()[0].action,null); assert.equal(calls,frozenCalls);
assert.deepEqual(transforms(),initial); assert.deepEqual([...root.position,...root.quaternion,...root.scale],frozenRoot);
api.update(26,.05); assert.equal(calls,frozenCalls+1);
root.position.y=.265;api.pet(root.name);for(let i=0;i<44;i++)api.update(26,.05);root.updateMatrixWorld(true);body.traverse(n=>{if(!n.geometry)return;const e=n.matrixWorld.elements;const r=n.geometry.type==='CylinderGeometry'?Math.hypot(e[1],e[9])+.5*Math.abs(e[5]):Math.hypot(e[1],e[5],e[9]);assert(e[13]-r>=.273-1e-9,'Belly pose must rest on current bridge level');});for(let i=0;i<76;i++)api.update(26,.05);
api.pet(root.name); api.update(26,.05); api.dispose(); assert.deepEqual(transforms(),initial);
api.update(27,.05); assert.equal(calls,frozenCalls+1); assert.equal(api.pet(root.name),false);
api.stopSound();
console.log('PASS deterministic scratch, root freeze, updater freeze/resume, belly support, interruption, exact restore, dt=0, dispose, Node audio fallback');
